                mid_f(i,j)=(min(blockv)+max(blockv))/2;
                sorted=sort(blockv);
                trimmed=sorted(alpha+1:end-alpha);
                alpha_f(i,j)=mean(trimmed);
            end
        end
        
        figure('Name', 'Nomor 5: Noise Filter Test', 'Position', [100 100 1200 700]);
        subplot(3,4,1);imshow(I_gray);title('Original');
