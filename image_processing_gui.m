        n = str2double(get(edit_n, 'String'));
        if isnan(n) || n < 1
            msgbox('Invalid filter size!', 'Error', 'error');
            return;
        end
        
        mean_filter = ones(n) / (n^2);
        data.processed_img = konvolusi_citra(data.original_img, mean_filter);
        display_processed();
        msgbox(sprintf('Mean filter applied (%dx%d)', n, n), 'Nomor 2');
    end

    function gaussian_filter_callback(~, ~)
        if isempty(data.original_img)
            msgbox('Please load an image first!', 'Warning', 'warn');
            return;
        end
        
        n = str2double(get(edit_n, 'String'));
        if isnan(n) || n < 1
            msgbox('Invalid filter size!', 'Error', 'error');
            return;
        end
        
        sigma = n / 6;
        [x, y] = meshgrid(-floor(n/2):floor(n/2), -floor(n/2):floor(n/2));
        gauss_filter = exp(-(x.^2 + y.^2) / (2 * sigma^2));
        gauss_filter = gauss_filter / sum(gauss_filter(:));
        
        data.processed_img = konvolusi_citra(data.original_img, gauss_filter);
        display_processed();
        msgbox(sprintf('Gaussian filter applied (%dx%d)', n, n), 'Nomor 2');
    end

