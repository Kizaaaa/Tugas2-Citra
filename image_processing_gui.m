        subplot(3,4,8);imshow(harm_f);title('Harmonic');
        subplot(3,4,9);imshow(contra_f);title('Contraharmonic');
        subplot(3,4,10);imshow(mid_f);title('Midpoint');
        subplot(3,4,11);imshow(alpha_f);title('Alpha-trimmed');
