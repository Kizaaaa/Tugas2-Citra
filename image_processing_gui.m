            return;
        end
        
        [M, N] = size(img);
        P = 2*M;
        Q = 2*N;
        
        image = im2double(img);
        imagep = zeros(P, Q);
        for i = 1:P
            for j = 1:Q
                if i <= M && j <= N
                    imagep(i,j) = image(i,j);
                end
            end
        end
        
        F = fftshift(fft2(imagep));
        
        u = 0:(P-1);
        v = 0:(Q-1);
        idx = find(u > P/2);
        u(idx) = u(idx) - P;
        idy = find(v > Q/2);
        v(idy) = v(idy) - Q;
        
        [V, U] = meshgrid(v, u);
        D = sqrt(U.^2 + V.^2);
        
        switch filter_type
            case 'ihpf'
                H = double(D > D0);
                fname = 'IHPF';
            case 'ghpf'
                H = exp(-(D.^2)./(2*(D0^2)));
                H = 1 - H;
                fname = 'GHPF';
            case 'bhpf'
                D(D == 0) = 0.01;
                n = 2;
                H = 1 ./ (1 + (D0./D).^(2*n));
                fname = 'BHPF';
        end
        
        H = fftshift(H);
        
        G = H .* F;
        G1 = ifftshift(G);
        G2 = real(ifft2(G1));
        G2 = G2(1:M, 1:N);
        
        data.processed_img = mat2gray(G2);
        display_processed();
        msgbox(sprintf('%s applied (D0=%d)', fname, D0), 'Nomor 3 - Highpass Filter');
    end

    function highboost_callback(~, ~)
        if isempty(data.original_img)
            msgbox('Please load an image first!', 'Warning', 'warn');
            return;
        end
        
        D0 = str2double(get(edit_d0_hb, 'String'));
        k = str2double(get(edit_k, 'String'));
        
        if isnan(D0) || D0 < 1 || isnan(k) || k < 1
            msgbox('Invalid parameters!', 'Error', 'error');
            return;
        end
        
        img = data.original_img;
        if size(img, 3) == 3
            img_gray = rgb2gray(img);
        else
            img_gray = img;
        end
        
        I_gray = im2double(img_gray);
        [M, N] = size(I_gray);
        F = fft2(I_gray);
        F_shifted = fftshift(F);
        [u, v] = meshgrid(-floor(N/2):(ceil(N/2)-1), -floor(M/2):(ceil(M/2)-1));
        D = sqrt(u.^2 + v.^2);
        H_lowpass = exp(-(D.^2) / (2 * (D0^2)));
        H_highboost = (k - 1) + H_lowpass;
        G = H_highboost .* F_shifted;
        G_ishift = ifftshift(G);
        g = real(ifft2(G_ishift));
        data.processed_img = mat2gray(g);
        
        display_processed();
        msgbox(sprintf('High-Boost filter applied (D0=%d, k=%.2f)', D0, k), 'Nomor 4');
    end

