    function apply_frequency_filter(filter_type)
        if isempty(data.original_img)
            msgbox('Please load an image first!', 'Warning', 'warn');
            return;
        end
        
        D0 = str2double(get(edit_d0, 'String'));
        if isnan(D0) || D0 < 1
            msgbox('Invalid D0 value!', 'Error', 'error');
            return;
        end
        
        img = data.original_img;
        if size(img, 3) == 3
            img = rgb2gray(img);
        end
        
        image = im2double(img);
        [M, N] = size(image);
        
        [u, v] = meshgrid(0:N-1, 0:M-1);
        D = sqrt((u - N/2).^2 + (v - M/2).^2);
        
        H_ilpf = double(D <= D0);
        H_glpf = exp(-(D.^2) / (2 * (D0^2)));
        n_order = 2;
        H_blpf = 1 ./ (1 + (D./D0).^(2*n_order));
        
        switch filter_type
            case 'ilpf'
                H = H_ilpf;
                fname = 'ILPF';
            case 'glpf'
                H = H_glpf;
                fname = 'GLPF';
            case 'blpf'
                H = H_blpf;
                fname = 'BLPF';
        end
        
        F = fftshift(fft2(image));
        G = F .* H;
        filtered = real(ifft2(ifftshift(G)));
        
        data.processed_img = im2uint8(mat2gray(filtered));
        display_processed();
        msgbox(sprintf('%s applied (D0=%d)', fname, D0), 'Nomor 2 - Lowpass Filter');
    end

