    function wiener_callback(~, ~)
        if isempty(data.original_img)
            msgbox('Please load an image first!', 'Warning', 'warn');
            return;
        end
        
        len = str2double(get(edit_len, 'String'));
        theta = str2double(get(edit_theta, 'String'));
        K = str2double(get(edit_K, 'String'));
        
        if isnan(len) || isnan(theta) || isnan(K)
            msgbox('Invalid parameters!', 'Error', 'error');
            return;
        end
        
        I = im2double(data.original_img);
        if size(I,3) == 3
            I = rgb2gray(I);
        end
        
        PSF = fspecial('motion', len, theta);
        I_blur = imfilter(I, PSF, 'conv', 'circular');
        H = psf2otf(PSF, size(I));
        G = fft2(I_blur);
        F_est = conj(H) ./ (abs(H).^2 + K) .* G;
        I_restored = real(ifft2(F_est));
        
        data.processed_img = I_restored;
        display_processed();
        msgbox(sprintf('Wiener filter applied (len=%d, theta=%d, K=%.4f)', len, theta, K), 'Nomor 7');
    end

